export const WORK_PERMIT_TYPES = Object.keys(WORK_PERMIT_FORMS)

export function checklistFor(type) {
  return WORK_PERMIT_FORMS[type].checks.map((item, index) => {
    if (typeof item === 'string') return { no:index + 1, label:item, answer:'', remarks:'' }
    return { no:item.no, label:item.label, answer:'', remarks:'' }
  })
}

export function selectionMap(items) {
  return Object.fromEntries(items.map(item => [item, false]))
}
